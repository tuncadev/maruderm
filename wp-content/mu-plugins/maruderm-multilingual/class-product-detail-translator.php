    public function text(string $value, string $language): string
    {
        return $language === 'ru' ? (self::RUSSIAN[$value] ?? $value) : $value;
    }

    public function html(string $value, string $language): string
    {
        return $language === 'ru' ? strtr($value, self::RUSSIAN) : $value;
    }

    /** @param string[] $values @return string[] */
    public function strings(array $values, string $language): array
    {
        return array_map(fn (string $value): string => $this->text($value, $language), $values);
    }

    /** @param array<int, array{title: string, text: string}> $values */
    public function pairs(array $values, string $language): array
    {
        return array_map(fn (array $value): array => [
            'title' => $this->text((string) $value['title'], $language),
            'text' => $this->text((string) $value['text'], $language),
        ], $values);
    }
